// Regenerates scripts/schema.sql from lib/schema.js, so the paste-able file
// can't drift away from what the app actually creates.
//   node scripts/gen-schema-sql.js

const fs = require('fs')
const path = require('path')
const { STATEMENTS } = require('../lib/schema')

const header = `-- Generated by scripts/gen-schema-sql.js — edit lib/schema.js, not this file.
--
-- Paste this into your database provider's SQL editor and press Run. It does
-- the same thing as \`npm run setup-db\` and the "Set up database" button in
-- /admin, so you don't need a terminal to set the database up.
--
-- Safe to run more than once: every statement is IF NOT EXISTS.
`

const body = STATEMENTS.map(s => {
  const comment = s.comment ? `-- ${s.comment}\n` : `-- ${s.label}\n`
  return `${comment}${s.sql};`
}).join('\n\n')

const out = path.join(__dirname, 'schema.sql')
fs.writeFileSync(out, header + '\n' + body + '\n')
console.log('Wrote ' + out)
